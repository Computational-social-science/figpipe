class MutationError(RuntimeError):
    """The mutation loop was asked to do something it cannot do honestly."""


class BudgetExceeded(MutationError):
    """A probe would exceed the declared rollout budget. Raised BEFORE the rollout runs."""


#: The two outcomes a task can declare. Anything else is a contract violation.
EXPECTATIONS = ("refused", "clean")


# --------------------------------------------------------------------------------------
# Propose
# --------------------------------------------------------------------------------------

@dataclass(frozen=True)
class Task:
    """One fixed probe task: a dataset, the skill call, and what the RIGHT outcome is.

    `data` is a factory, not a frame, so a probe cannot mutate the shared fixture and make a
    later candidate look better by accident. `expect` is the specification the probe is scored
    against; see the module docstring for why it is two-sided.
    """
    id: str
    skill: str
    params: dict
    data: object
    expect: str
    why: str
    #: The rendered figure this task's style is measured AGAINST, or None.
    #:
    #: A refusal task has no reference figure -- its question is "should this be rejected" and the
    #: answer has no style content. A STYLE task declares one, and `_style_score` then compares the
    #: two rendered profiles. None means "not applicable", which is why the reward is absent rather
    #: than 0.0.
    reference_pdf: str | None = None

    def frame(self) -> pd.DataFrame:
        return self.data()


@dataclass(frozen=True)
class Candidate:
    """One proposed edit to one operator parameter, with the reason it is worth probing.

    A candidate is DATA. It names the operator parameter, the baseline value and its own value,
    so the contrast between two probes is the contrast between two declared numbers -- not a diff
    of generated code.
    """
    id: str
    operator: str
    parameter: str
    baseline_value: object
    value: object
    rationale: str
    skill: str

    def to_dict(self) -> dict:
        return dataclasses.asdict(self)


@dataclass(frozen=True)
class MutationSpace:
    """The declared space: which candidates may be proposed, over which fixed tasks."""
    candidates: tuple[Candidate, ...]
    tasks: tuple[Task, ...]
    min_margin: float = 0.10
    #: An ABSOLUTE quality target, on the same 0..1 scale as a task score.
    #:
    #: WHY: `min_margin` answers "is this edit better than doing nothing", which is a RELATIVE
    #: question. It cannot answer "is the result good enough to ship". Without a target the loop
    #: selects the least-bad available edit even when every candidate is a tie -- reporting motion
    #: as progress. AutoFigure (ICLR 2026) calls this `quality_threshold` and stops refining once a
    #: figure clears it; the same idea applies here.
    #:
    #: None means "no target": the loop keeps its relative-only behaviour and SAYS SO in the
    #: result, rather than implying a standard it never applied.
    min_score: float | None = None

    def __post_init__(self) -> None:
        """A target outside 0..1 is a typo, not a policy -- refuse it at construction.

        Silently accepting `min_score=90` (a percentage where a fraction was meant) would make
        every edit "below target" and the loop would never select anything, with no error to
        explain why.
        """
        if self.min_score is not None:
            if not isinstance(self.min_score, (int, float)):
                raise MutationError(f"min_score must be a number, got {self.min_score!r}")
            if not 0.0 <= float(self.min_score) <= 1.0:
                raise MutationError(
                    f"min_score must be within 0..1 (task scores are fractions), got "
                    f"{self.min_score!r}; a percentage such as 90 would make every edit look "
                    f"below target")
        if not 0.0 < float(self.min_margin) <= 1.0:
            raise MutationError(f"min_margin must be within 0..1, got {self.min_margin!r}")

    def candidate(self, cid: str) -> Candidate:
        for c in self.candidates:
            if c.id == cid:
                return c
        raise MutationError(f"no candidate {cid!r} in the space; have "
                            f"{[c.id for c in self.candidates]}")


def propose(space: MutationSpace) -> dict:
    """Enumerate the candidates as data, with the checks that make a proposal honest.

    Three things are refused here rather than discovered during probing: a duplicate id (two
    different edits indistinguishable in the record), a candidate that does not change anything (a
    guaranteed tie that wastes rollouts), and a candidate whose skill cannot receive its parameter
    (which would be scored as a refusal for a reason that has nothing to do with the budget).
    """
    seen: set[str] = set()
    for c in space.candidates:
        if c.id in seen:
            raise MutationError(f"duplicate candidate id {c.id!r}")
        seen.add(c.id)
        if c.value == c.baseline_value:
            raise MutationError(
                f"candidate {c.id!r} sets {c.operator}.{c.parameter} to its baseline value "
                f"{c.value!r}; a no-op candidate cannot produce a contrast")
        if not c.rationale.strip():
            raise MutationError(f"candidate {c.id!r} has no rationale")
        if c.operator not in skills.OPERATORS:
            raise MutationError(f"candidate {c.id!r} names unknown operator {c.operator!r}")
        if c.skill not in skills.SKILLS:
            raise MutationError(f"candidate {c.id!r} names unknown skill {c.skill!r}")
        contract = skills.SKILLS[c.skill]
        allowed = set(contract.required) | set(contract.optional) | {"profile"}
        if c.parameter not in allowed:
            raise MutationError(
                f"candidate {c.id!r} edits {c.parameter!r}, which skill {c.skill!r} does not "
                f"accept (it would be refused for the wrong reason); its contract is "
                f"{sorted(allowed)}")
    if not space.tasks:
        raise MutationError("a mutation space needs at least one task")
    ids = [t.id for t in space.tasks]
    if len(set(ids)) != len(ids):
        raise MutationError(f"duplicate task ids in the space: {ids}")
    for t in space.tasks:
        if t.expect not in EXPECTATIONS:
            raise MutationError(f"task {t.id!r} declares expect={t.expect!r}; "
                                f"expected one of {EXPECTATIONS}")
        if t.skill not in skills.SKILLS:
            raise MutationError(f"task {t.id!r} names unknown skill {t.skill!r}")
    return {
        "candidates": [c.to_dict() for c in space.candidates],
        "tasks": [{"id": t.id, "skill": t.skill, "expect": t.expect, "why": t.why}
                  for t in space.tasks],
        "min_margin": space.min_margin,
        "note": ("proposals are declared, not generated: every candidate names the parameter it "
                 "changes, its baseline value, the skill that must accept it, and the defect "
                 "history that motivates it"),
    }


