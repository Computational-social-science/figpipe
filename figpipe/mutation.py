"""Propose - Probe - Compose: a deterministic mutation loop over figpipe's own operators.

WHY THIS MODULE EXISTS
    figpipe's refusals are its most valuable behaviour and its least examined one.
    `layout.split_panels` refuses a bar axis past 12 categories; `encode.matrix` refuses a long
    table with no 2-D reading past 40 rows. Both budgets were chosen once, by hand, after a real
    defect (LEARNINGS ##46), and nothing has re-derived them since. A budget is a CLAIM -- "this is
    the right threshold" -- and an unexamined claim in this project is the defect family LEARNINGS
    keeps recording.

    The peer project harness2 (google-research/harness2, Apache 2.0) has the right shape for
    auditing such claims: a contrastive **Propose -> Probe -> Compose** step. Propose candidate
    edits, PROBE each by executing it on the SAME task, and COMPOSE a decision from the
    behavioural contrast between the executions, without ground truth. This module implements that
    shape over figpipe's operators, DETERMINISTICALLY: no LLM, no network, no API key. Two runs
    over the same space and the same task set produce identical decisions, which is the property
    harness2 gives up by using a model and the one this project cannot give up.

WHAT IS REUSED FROM harness2, AND WHAT IS NOT
    Reused, vendored unmodified: `third_party/harness2_ledger/ledger.py` -- pure-stdlib budget
    accounting (see its NOTICE.md for the commit sha and the byte-identity check).
    Reused as a design: the propose/probe/compose separation, and "a probe is an execution, not an
    opinion".
    NOT reused: `proposer.py`, `selection.py`, `recursion.py`, which drive model sessions. Their
    selection step asks a model to choose; this module's `compose` compares measured outcomes and
    REFUSES to choose on a tie.

THE THREE STAGES
    propose()  enumerate candidate edits from a DECLARED space. Every candidate is data -- an id,
    the operator parameter it changes, its old and new value, and a rationale naming the defect
    history that makes it worth trying. Nothing is generated by a model, so a candidate can be
    argued with.
    probe()    run EVERY candidate AND the baseline on a fixed task set, recording an outcome per
    (candidate, task). It runs under `figpipe.lock.measure("mutation")`: overlapping measurements
    on this machine produce numbers nobody can trust (LEARNINGS ##55), and the lock is the
    enforcement rather than the convention.
    compose()  decide from the behavioural contrast. A candidate is SELECTED only when it beats
    the baseline by at least `min_margin`; REJECTED when it is worse; and a tie is reported as a
    tie. A tie must never silently pick one.

THE SCORE: A REFUSAL IS NOT A FAILURE, AND A CLEAN RENDER IS NOT AUTOMATICALLY A SUCCESS
    Each task DECLARES what the right outcome is -- `expect="refused"` or `expect="clean"` -- and
    the probe is judged against that declaration:

        outcome matches the declared expectation      -> 1.0
        refused when it should have rendered          -> 0.0   (lost capability, no excuse)
        rendered with hard findings when it should    -> 1 - n/(n+1)   (0.5 for one, 0.05 for 19)
        crashed                                       -> 0.0   (an edit that breaks a skill)

    The two-sided contract is the point. A one-sided "refusals are always good" score cannot see a
    budget that is too TIGHT: `encode.matrix` at 40 rows refuses a 41-row table that renders with
    ZERO collisions (measured, see `default_space`), and a score that rewarded every refusal would
    call that correct forever. A one-sided "renders are always good" score would instead reward
    `max_rows=60`, which draws 96 colliding tick labels. Neither alone can tell a correct refusal
    from a timid one, so the task set states its expectation and the loop measures the distance
    from it.

WHAT THIS DOES NOT DO (stated, not implied)
    * It does not tune the operators automatically. It PROPOSES, PROBES and DECIDES; a human (or a
      later round) still has to accept the selected value into the code. Applying a decision is out
      of scope on purpose: an automatic writer that changed a budget on the strength of five tasks
      would be the "a fix is a change, a change needs the same evidence" defect (##47).
    * The expectations are DECLARED, not derived, by the probe. They were measured once, by hand,
      with `max_bars`/`max_rows` forced open (the numbers are in each task's `why`), and they are
      what the loop holds fixed. The loop therefore audits the budgets against a specification; it
      does not discover the specification. That is a weaker claim than "the loop finds the right
      budget", and it is the claim the code supports.
    * The task set is FIXED and small (5 tasks). That satisfies the rule every judged metric in
      this project now obeys -- a function of a fixed task set and a single instrument version
      (##42, ##43) -- but a small set is a small set: it can only distinguish the candidates it
      contains. It is a check on a budget, not a re-derivation of it.
    * The score is a proxy for legibility, not a measurement of it. It counts hard audit findings
      and refusals; it does not know whether a reader can read the axis. Its justification is that
      the budgets it defends were themselves derived from glyph-collision measurements (##46).
"""
