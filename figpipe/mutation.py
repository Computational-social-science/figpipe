#: Label length matters and that is not a detail: 20 SHORT labels ("o0".."o19") render with ZERO
#: collisions even at 20 bars, so a fixture with short labels would have made the MAX_BARS
#: refusal look arbitrary and the whole loop look like it worked. Measured with the budget forced
#: open: short -> 0 hard findings, `outcome_00..outcome_19` -> 19. The long labels are used below
#: because they are the case the budget exists for.
_LONG_LABELS = tuple(f"outcome_{i:02d}" for i in range(20))


def _many_long_categories() -> pd.DataFrame:
    """20 long-named categories per panel: past any sane bar budget, and they DO collide."""
    return pd.DataFrame({
        "panel_group": ["A"] * 20 + ["B"] * 20,
        "outcome": list(_LONG_LABELS) * 2,
        "estimate": [0.1 + 0.01 * i for i in range(40)],
    })


def _few_categories() -> pd.DataFrame:
    """6 categories per panel: inside the budget, so a clean render is the right answer."""
    return pd.DataFrame({
        "panel_group": ["A"] * 6 + ["B"] * 6,
        "outcome": [f"outcome_{i:02d}" for i in range(6)] * 2,
        "estimate": [0.1 + 0.01 * i for i in range(12)],
    })


def _wide_matrix() -> pd.DataFrame:
    """A genuine matrix: 6 x 5 numeric, nothing to pivot, nothing to refuse."""
    return pd.DataFrame({f"c{i}": [0.1 * i + 0.01 * j for j in range(6)] for i in range(5)})


def _unpivotable(rows: int):
    """A table whose only numeric columns are (x, v), both varying: no 2-D reading exists."""
    def make() -> pd.DataFrame:
        return pd.DataFrame({"x": [float(i) for i in range(rows)],
                             "v": [float((i * 7) % 13) for i in range(rows)]})
    return make


def _real_matrix() -> pd.DataFrame:
    """40 rows x 10 cols with string row labels -- the shape the benchmark actually uses."""
    return _matrix_frame(40, 10, string_index=True)


def _matrix_frame(n_rows: int, n_cols: int = 2, *, string_index: bool = True):
    """A matrix shaped like the REAL benchmark tasks, not like a convenient fixture.

    The first version used an integer index, and the drawer hides ticks for numeric indices -- so
    the fixture never touched the label path that produces up to 405 collisions on the real pool.
    Real tasks carry STRING indices (row labels), which is what makes the axis over-full.
    """
    # deterministic, no RNG: a fixed irrational-style ramp keeps the fixture reproducible without
    # importing numpy, which the module's allow-list deliberately excludes
    values = [[((i * 7 + j * 13) % 97) / 97.0 for j in range(n_cols)] for i in range(n_rows)]
    index = [f"row{i}" for i in range(n_rows)] if string_index else None
    return pd.DataFrame(values, index=index)


#: WHY THE FIXTURE MUST LOOK LIKE PRODUCTION
#:
#: The first version of this space selected `matrix-max-rows-41` (+0.167). Re-measuring the real
#: pool showed the selection was WRONG: 13 of 14 `matrix_plate` benchmark tasks already had hard
#: collisions at the CURRENT budget of 40, summing 995 findings with a worst case of 405. Raising
#: the budget would have made every one of them worse.
#:
#: The fixture could not have found that, for two reasons:
#:   * its matrix tables used an INTEGER index, and the drawer hides ticks for numeric indices --
#:     so the label path that produces the collisions was never exercised
#:   * its "unpivotable" tables are refused by the pivot rule before reaching the drawer at all
#:
#: A mutation loop is only as good as the distribution it probes. Six convenient tasks selected a
#: worse world, confidently, and the loop had no way to know. That is the same defect as a
#: benchmark measured on a convenient subset, one layer in.


def default_space() -> MutationSpace:
    """The first declared space: the two refusals from LEARNINGS ##46, plus their controls.

    Each candidate is paired with an expectation about the VERDICT, so the loop is judged on
    whether it can tell an improvement from a regression from a tie -- not on whether it finds an
    improvement somewhere.

      split_panels max_bars 12 -> 24   EXPECTED: rejected. 20 long labels collide (19 hard
                                       findings, measured), so relaxing the budget trades a
                                       correct refusal for an unreadable figure.
      split_panels max_bars 12 -> 13   EXPECTED: tie. No task in the set has 13..24 categories,
                                       so the task set cannot distinguish the two budgets.
      matrix max_rows 40 -> 41         EXPECTED: selected. Measured with the budget forced open:
                                       41 unpivotable rows render with ZERO collisions and 42
                                       rows produce 41. The budget of 40 is therefore one row
                                       inside the boundary and refuses a table it could draw.
      matrix max_rows 40 -> 42         EXPECTED: rejected. It fixes the 41-row table but admits
                                       the 42-row one, which produces 41 collisions.
      matrix max_rows 40 -> 60         EXPECTED: rejected. Same trade, larger: it renders the
                                       48-row table with 96 hard findings.

    Note what is NOT in the space: `max_panels`. Probing it found that raising it produces a
    COMPOSER refusal ("5 panels do not fill a 2x3 grid"), so it exercises `composite`, not the
    operator's own budget. Including it would have made the loop look broader than it is.
    """
    tasks = (
        Task("split-many-bars", "composite_groups",
             {"by": "panel_group", "x": "outcome", "y": "estimate"}, _many_long_categories,
             "refused",
             "20 long categories per panel: refusing is correct (forced open, it renders with 19 "
             "text collisions)"),
        Task("split-few-bars", "composite_groups",
             {"by": "panel_group", "x": "outcome", "y": "estimate"}, _few_categories,
             "clean",
             "6 categories per panel: a render with no hard findings is correct"),
        # A REAL-SHAPED matrix: 40 rows x 10 cols with a STRING index, exactly like the benchmark
        # tasks that produced up to 405 collisions. The earlier fixture used a 41x2 integer-index
        # table, which the pivot rule refuses outright -- so it never reached the drawer and the
        # loop could not see the defect it was supposed to find.
        Task("matrix-real-40x10", "matrix_plate", {}, _real_matrix, "clean",
             "a 40x10 matrix with row labels, as the benchmark has"),
        Task("matrix-wide", "matrix_plate", {}, _wide_matrix,
             "clean",
             "a genuine 6x5 matrix: renders, so the row budget must not start refusing it"),
        Task("matrix-41-rows", "matrix_plate", {}, _unpivotable(41),
             "clean",
             "41 unpivotable rows: forced open it renders with 0 collisions, so the correct "
             "outcome is a render and the 40-row budget refuses one row too early"),
        Task("matrix-42-rows", "matrix_plate", {}, _unpivotable(42),
             "refused",
             "42 unpivotable rows: forced open it renders with 41 collisions, so refusing is "
             "correct -- and this task is what makes a blanket relaxation a REJECTION rather "
             "than a gain"),
        Task("matrix-48-rows", "matrix_plate", {}, _unpivotable(48),
             "refused",
             "48 unpivotable rows: forced open it renders with 96 collisions, so refusing is "
             "correct"),
    )
    candidates = (
        Candidate(
            id="split-max-bars-24", operator="layout.split_panels", parameter="max_bars",
            baseline_value=skills.MAX_BARS, value=24,
            rationale=("LEARNINGS ##46 set the category budget at 12 because 20 year-bars "
                       "produced 19 collisions. Relaxing it to 24 lets that defect back in; the "
                       "probe measures whether the task set still sees it."),
            skill="composite_groups"),
        Candidate(
            id="split-max-bars-13", operator="layout.split_panels", parameter="max_bars",
            baseline_value=skills.MAX_BARS, value=13,
            rationale=("an off-by-one relaxation: if 12 were too tight, one extra category would "
                       "recover a refusal at no legibility cost. The probe asks whether any task "
                       "can tell the two budgets apart."),
            skill="composite_groups"),
        Candidate(
            id="matrix-max-rows-41", operator="encode.matrix", parameter="max_rows",
            baseline_value=skills.MAX_MATRIX_ROWS, value=41,
            rationale=("the row budget is one row tighter than the measured collision boundary: "
                       "41 unpivotable rows render with 0 collisions and 42 produce 41. If that "
                       "holds on the task set, the budget refuses a table it could draw."),
            skill="matrix_plate"),
        Candidate(
            id="matrix-max-rows-42", operator="encode.matrix", parameter="max_rows",
            baseline_value=skills.MAX_MATRIX_ROWS, value=42,
            rationale=("one row past the measured boundary: it admits the 48-row table, whose "
                       "tick labels collide. The expected verdict is a rejection, so this is the "
                       "negative control for 'any relaxation is a gain'."),
            skill="matrix_plate"),
        Candidate(
            id="matrix-max-rows-60", operator="encode.matrix", parameter="max_rows",
            baseline_value=skills.MAX_MATRIX_ROWS, value=60,
            rationale=("LEARNINGS ##47 records the row budget as a refusal that was nearly a "
                       "regression. Relaxing it to 60 re-admits the 48-row table and tests "
                       "whether the collisions it was protecting against are still there."),
            skill="matrix_plate"),
    )
    return MutationSpace(candidates=candidates, tasks=tasks, min_margin=0.10)


def run(space: MutationSpace | None = None, *, budget: int | None = None,
        out_dir=None, min_margin: float | None = None) -> dict:
    """The whole loop: propose -> probe -> compose, with the ledger attached to the result."""
    space = space or default_space()
    proposal = propose(space)
    probed = probe(space, budget=budget, out_dir=out_dir)
    decision = compose(probed, space, min_margin=min_margin)
    return {"proposal": proposal, "probe": probed, "compose": decision}


