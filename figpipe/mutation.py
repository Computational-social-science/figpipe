def _render_score(hard_failures: int) -> float:
    """`1 - n/(n+1)`: 0 hard findings -> 1.0, 1 -> 0.5, 2 -> 0.667, 19 -> 0.05."""
    n = max(0, int(hard_failures))
    return round(1.0 - n / (n + 1), 6)


def _score(task: Task, outcome: str, hard_failures: int = 0) -> float:
    """Judge one outcome against the task's declared expectation.

    A refusal scores 1.0 only when refusal was the RIGHT answer. That asymmetry is the whole
    reason the task declares `expect`: without it, "refuse everything" would be a perfect score.
    """
    if outcome == "crashed":
        return 0.0
    if outcome == "refused":
        return 1.0 if task.expect == "refused" else 0.0
    return _render_score(hard_failures)


def run_task(task: Task, override: dict | None = None) -> dict:
    """Execute one task once and classify the outcome. Never raises for a refusal or a crash.

    A REFUSAL is a first-class outcome, not an error: it is what these operators are supposed to
    do when an encoding cannot carry the data. An unexpected exception is scored 0.0 and its type
    is recorded, because a crash IS a failure of the edit.
    """
    params = dict(task.params)
    params.update(override or {})
    stem = _probe_stem(task.id, override)
    try:
        res = skills.run(task.skill, task.frame(), out_stem=stem, **params)
    except skills.SkillError as exc:
        return {"task": task.id, "outcome": "refused", "score": _score(task, "refused"),
                "expected": task.expect, "detail": str(exc)[:300]}
    except Exception as exc:                                    # noqa: BLE001 - classified
        return {"task": task.id, "outcome": "crashed", "score": 0.0, "expected": task.expect,
                "detail": f"{type(exc).__name__}: {exc}"[:300]}
    hard = [f for f in res["findings"] if f["severity"] == "hard"]
    row = {"task": task.id, "outcome": "rendered", "score": _score(task, "rendered", len(hard)),
           "expected": task.expect, "hard_failures": len(hard),
           "checks": sorted({f["check"] for f in hard}),
           "panels": res["panels"], "pdf": res["pdf"]}
    # THE STYLE REWARD. `score` above answers "was this outcome correct"; it cannot answer "does this
    # figure LOOK like the reference", and it is 1.0 for every task in the pool, so it ranks nothing.
    #
    # This reads the emitted PDF through the benchmark's own scorer against the reference the task
    # declares. It is REPORTED SEPARATELY: merging two different questions into one number is how a
    # reward stops being legible (LEARNINGS ##161).
    style_score = _style_score(task, row.get("pdf"))
    if style_score is not None:
        row["style_score"] = style_score
    return row


def _style_score(task: Task, pdf_path: str | None) -> float | None:
    """The benchmark's own style score for a rendered figure, or None when it cannot be measured.

    None is a real answer: a task with no declared reference has no style to match, and reporting 0.0
    would read as "matched nothing" rather than "not applicable".
    """
    reference = getattr(task, "reference_pdf", None)
    if not reference or not pdf_path:
        return None
    try:
        import pathlib as _p
        import sys as _sys
        _root = _p.Path(__file__).resolve().parents[1]
        for _cand in (_root, _root / "third_party"):
            if str(_cand) not in _sys.path:
                _sys.path.insert(0, str(_cand))
        import plottwin_scorer as _official
    except Exception:                               # noqa: BLE001 - optional, CC BY-NC
        return None
    # THE BENCHMARK HAS NO PDF SCORER -- `score_code_deviation` takes two CODE strings. What it
    # scores is the STYLE, and for a rendered figure the style is what `styleprofile` measures.
    # `styleprofile.compare` returns a distance in 0..1, so the reward is `1 - distance`: higher is
    # better, on the same scale as every other score in this module.
    try:
        from figpipe import styleprofile as _sp
        a = _sp.StyleProfile.from_pdf(reference)
        b = _sp.StyleProfile.from_pdf(pdf_path)
        dist = (_sp.compare(a, b) or {}).get("distance")
    except Exception:                               # noqa: BLE001 - a scorer failure is not a score
        return None
    if not isinstance(dist, (int, float)):
        return None
    return round(max(0.0, min(1.0, 1.0 - float(dist))), 6)


def _probe_stem(task_id: str, override: dict | None) -> pathlib.Path:
    """A private per-(task, edit) output stem under an ignored directory.

    THE PID IS PART OF THE PATH, and that is a bug fix, not tidiness. The first version keyed the
    stem on the task and the override only, so two probes running in DIFFERENT PROCESSES (a pytest
    run and a scheduled run, or two workers) wrote the same `templates/mutation/<task>--<edit>.pdf`
    at the same time. One process would `savefig` over the file while the other was still reading
    it back for the collision check, and the reader got
    `EmptyFileError: Cannot open empty file`. It was found by running the loop five times in
    separate processes and watching `split-few-bars` flip between "rendered" and "crashed" -- the
    overlapping-measurement hazard `figpipe.lock` exists to prevent, reached through the
    FILESYSTEM instead of the lock file.

    The lock still serialises probes on this machine; the pid makes the artefacts private even
    when something ignores it. Determinism is not lost: the DECISION depends on the outcomes, and
    the record stores each outcome, not its path. Two runs produce the same verdict and the same
    scores; only the throwaway render paths differ.
    """
    def _token(value):
        """A path-safe token for one override value.

        A scalar renders as itself. Anything else renders as `<type>-<8 hex>`, because a
        `StyleProfile`'s repr contains characters Windows rejects in a filename -- measured
        `OSError [WinError 123]` -- and the crash was being scored as a failed candidate.
        """
        if isinstance(value, (int, float, str, bool)) or value is None:
            return str(value)
        import hashlib as _h
        import reprlib as _r
        digest = _h.sha256(_r.repr(value).encode("utf-8")).hexdigest()[:8]
        return f"{type(value).__name__}-{digest}"

    suffix = "-".join(f"{k}={_token(v)}" for k, v in sorted((override or {}).items()))
    # Windows rejects these in a filename, and a path is not the place to discover that
    safe = (suffix or "baseline").replace(" ", "").replace("/", "_")
    for _bad in ('<', '>', ':', '"', '|', '?', '*', '\\'):
        safe = safe.replace(_bad, "_")
    return ROOT / "templates" / "mutation" / f"{task_id}--{safe}--p{os.getpid()}"


def _charge(ledger: Ledger, label: str, budget: int) -> None:
    """Count one rollout, refusing to exceed `budget` -- BEFORE the rollout is executed.

    The vendored ledger is a RECORDER: it can only complain after the fact (see its NOTICE.md).
    The refusal has to happen here, or a 12-rollout budget would happily spend 13 and report the
    overspend afterwards, which is a report and not a control.
    """
    if ledger.R >= budget:
        raise BudgetExceeded(
            f"rollout budget exhausted: {ledger.R} of {budget} already spent, refusing to "
            f"probe {label!r}. Raise the budget deliberately or probe fewer candidates.")
    ledger.rollout(label)


def probe(space: MutationSpace, *, budget: int | None = None, out_dir=None,
          lock_held: bool = False) -> dict:
    """Run the baseline and every candidate over the fixed task set, one rollout at a time.

    The whole loop holds `figpipe.lock.measure("mutation")`. If the lock refuses, that is the
    correct outcome and it propagates as `lock.MeasurementBusy`: two overlapping measurements on
    this machine produce numbers that are neither reproducible nor trustworthy (LEARNINGS ##55).

    An override reaches ONLY the tasks of the candidate's own skill. Passing it to every task is
    a real defect this loop had on its first run: `max_bars` sent to `matrix_plate` made two
    matrix tasks "refuse" with "does not understand parameters ['max_bars']", which the score
    read as a correct refusal and which masked the split-panel contrast entirely.

    Budget: the default is `len(tasks) * (1 + len(candidates))` -- exactly what the loop needs --
    so the check is live rather than decorative. A caller may pass a smaller one, and the probe
    will RAISE rather than silently probe a subset: a decision composed from a partial probe would
    compare candidates on different task sets, which is the measurement defect this project has
    recorded five times (##25, ##26, ##30, ##42, ##43).
    """
    need = len(space.tasks) * (1 + len(space.candidates))
    budget = need if budget is None else int(budget)
    ledger = Ledger(mode="mutation", task_id=",".join(t.id for t in space.tasks), k=0)
    rows: dict[str, dict] = {}
    # `lock_held=True` means the CALLER already holds the measurement lock (cron_run runs this as a
    # child process). Re-acquiring would deadlock against our own parent -- the same defect already
    # fixed for the benchmark harness.
    ctx = _nullcontext() if lock_held else lock.measure("mutation")
    with ctx:
        for task in space.tasks:
            _charge(ledger, f"baseline:{task.id}", budget)
            rows.setdefault("baseline", {})[task.id] = run_task(task)
        for cand in space.candidates:
            for task in space.tasks:
                _charge(ledger, f"{cand.id}:{task.id}", budget)
                override = {cand.parameter: cand.value} if task.skill == cand.skill else {}
                rows.setdefault(cand.id, {})[task.id] = run_task(task, override)
    ledger.session("compose")
    out = {
        "space": {"min_margin": space.min_margin,
                  "candidates": [c.id for c in space.candidates],
                  "tasks": [t.id for t in space.tasks]},
        "outcomes": rows,
        "mean_score": {name: _mean([r["score"] for r in per_task.values()])
                       for name, per_task in rows.items()},
        # THE STYLE AGGREGATE, SEPARATE ON PURPOSE.
        #
        # `mean_score` above is the refusal classifier, and it is 1.0 for every task in the pool -- so
        # every contrast it can express is 0.0, which is where the 222 ties came from. `mean_style` is
        # the same aggregation over `style_score`, present only for tasks that declare a reference.
        #
        # MERGING THEM WOULD BE THE DEFECT, not the fix: two different questions sharing one number is
        # how a reward stops being legible. `compose` chooses which to use and records the choice.
        "mean_style": {name: _mean([r["style_score"] for r in per_task.values()
                                    if isinstance(r.get("style_score"), (int, float))])
                       for name, per_task in rows.items()
                       if any(isinstance(r.get("style_score"), (int, float))
                              for r in per_task.values())},
        "ledger": ledger.to_dict(),
        "budget": budget,
        "note": ("ledger.R counts executions; expected_R/expected_P are harness2's 4k/3k "
                 "rollout schedule, which is NOT this loop's shape, so only R, P and the "
                 "labels are used here. The budget is enforced in _charge, before each "
                 "rollout -- the vendored ledger itself is a recorder."),
    }
    if out_dir is not None:
        path = pathlib.Path(out_dir)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps(out, indent=2) + "\n", encoding="utf-8")
        out["record"] = str(path)
    return out


def _mean(values: list[float]) -> float:
    return round(sum(values) / len(values), 6) if values else 0.0


