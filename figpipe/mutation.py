def _verdict(delta: float, drops: list, margin: float,
             score: float | None = None,
             min_score: float | None = None) -> tuple[str, str]:
    """The decision rule, as one pure function: (verdict, reason) for one candidate.

    Kept separate from `compose` so it can be INVERTED by a test. `tests/test_mutation.py` swaps
    this function for one that selects on a regression and rejects on an improvement, and asserts
    that the selection tests then FAIL. A test that cannot fail is not a test (LEARNINGS ##48);
    a decision rule that cannot be shown to matter is not a control either.
    """
    if drops:
        worst = max(drops, key=lambda d: d["fell_by"])
        return "rejected", (
            f"regresses {len(drops)} task(s) on the fixed set, worst {worst['task']!r} by "
            f"-{worst['fell_by']:.3f} (>= margin {margin}); a task that gets worse is a "
            f"regression whatever the mean says")
    if delta >= margin:
        # THE ABSOLUTE TARGET. A relative improvement is not a pass: an edit can beat the baseline
        # and still leave the figure below the standard. Saying "selected" without that distinction
        # reports motion as progress.
        if min_score is not None and score is not None and score < min_score:
            return "selected", (
                f"improves the fixed task set by {delta:+.3f} (>= margin {margin}) with no task "
                f"regressing, but the result scores {score:.3f} -- BELOW the target {min_score:.3f}: "
                f"this edit helps and is still not good enough to ship")
        if min_score is not None:
            return "selected", (
                f"improves the fixed task set by {delta:+.3f} (>= margin {margin}) with no task "
                f"regressing, and reaches {score:.3f} (>= target {min_score:.3f})")
        return "selected", (
            f"improves the fixed task set by {delta:+.3f} (>= margin {margin}) with no task "
            f"regressing")
    if delta <= -margin:
        return "rejected", (
            f"regresses the fixed task set by {delta:+.3f} (<= -margin {margin})")
    if delta > 0:
        return "tie", (
            f"improves by {delta:+.3f}, below the margin {margin}: smaller than the decision "
            f"threshold, so it is reported as a tie rather than picked")
    return "tie", (
        f"no measurable difference on the fixed task set ({delta:+.3f}); the task set cannot "
        f"distinguish this edit from the baseline, so it is reported as a tie")


def probe_patch(patch, tasks, *, baseline_runner, patched_runner,
                out_dir=None) -> dict:
    """Probe ONE code patch, producing the same shape `probe` does.

    WHY A SEPARATE ENTRY POINT AND NOT A FLAG ON `probe`
        `probe` applies an override PER TASK (`params.update({parameter: value})`). A patch edits
        the SOURCE, so it must be applied ONCE around every task of the candidate and reverted
        afterwards. Putting both in one function would mean a flag that changes the apply/restore
        discipline, and that is exactly the kind of switch that ends up wrong in one branch.

    `baseline_runner()` and `patched_runner()` are supplied by the caller so this function never
    imports `patchprobe` -- the dependency points one way, and a test can drive it with stubs.

    Returns the same keys `compose` reads: `outcomes` and `mean_score`, plus `patch`.
    """
    base = baseline_runner()
    patched = patched_runner()
    rows = {"baseline": base, patch.id: patched}
    out = {
        "space": {"min_margin": 0.1,
                  "candidates": [patch.id],
                  "tasks": [t for t in tasks]},
        "outcomes": {name: {task: row for task, row in per.items()}
                     for name, per in rows.items()},
        "mean_score": {name: _mean([r["score"] for r in per.values()])
                       for name, per in rows.items()},
        "patch": patch.to_dict() if hasattr(patch, "to_dict") else dict(patch),
        "note": ("a CODE PATCH probe: the source was edited once around every task and restored "
                 "afterwards, so a crash cannot leave the tree modified"),
    }
    if out_dir is not None:
        path = pathlib.Path(out_dir)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps(out, indent=2) + "\n", encoding="utf-8")
        out["record"] = str(path)
    return out


def compose(probe_result: dict, space: MutationSpace, *,
            min_margin: float | None = None) -> dict:
    """Decide from the behavioural contrast; a tie is reported, never resolved.

    TWO conditions, because one is not enough:

    1. NO TASK MAY REGRESS. If any task's score falls by `min_margin` or more, the candidate is
       REJECTED whatever the mean says. This is the same rule the scheduled loop applies to
       capability fields (a judged field that gets worse fails the run), and it is here for a
       concrete reason: `max_rows=60` fixes the 41-row table AND makes the 48-row table collide,
       which nets out to +0.002 on the mean. A mean that cancels a broken figure against a fixed
       one is the "a mean over a set hides the case that matters" defect this project has
       recorded repeatedly (##25, ##26, ##30). The margin is the measurement's resolution, so a
       drop smaller than it is not a regression.
    2. THE MEAN MUST MOVE BY THE MARGIN. A candidate is SELECTED only when it beats the baseline
       by `min_margin` or more, in the same shape as `select.should_transfer` (keep the plain
       figure unless the styled one is at least `min_margin` closer). Otherwise it is a TIE.

    The three verdicts are different kinds of information and are kept apart on purpose: a
    REJECTION with a reason says "this edit does not help, and here is which task showed it"; a
    TIE says "the task set cannot distinguish these"; and picking one silently would be neither.
    """
    margin = space.min_margin if min_margin is None else float(min_margin)
    outcomes = probe_result["outcomes"]
    if "baseline" not in outcomes:
        raise MutationError("probe result has no baseline row; nothing to contrast against")
    # WHICH AGGREGATE IS BEING CLIMBED, said out loud.
    #
    # `mean_score` is the refusal classifier and is 1.0 for every task in the pool, so every contrast
    # on it is 0.0 -- that is the 222 ties. `mean_style` is present only when the task set declares
    # references, and when it is present it is the only aggregate with any resolution.
    #
    # A TIE ON A FLAT AGGREGATE IS NOT EVIDENCE OF "no difference"; it is evidence that the aggregate
    # cannot see. Recording which one was used is what lets a reader tell those apart.
    _style = probe_result.get("mean_style") or {}
    aggregate = "mean_style" if _style and "baseline" in _style else "mean_score"
    _means = _style if aggregate == "mean_style" else probe_result["mean_score"]
    base = _means["baseline"]
    # THE REFUSAL CLASSIFIER IS STILL CHECKED ON EVERY TASK, even when the style aggregate decides.
    #
    # `mean_style` covers only the tasks that declare a reference -- one task in the default space --
    # so a layout candidate's style delta is exactly 0.0 and a regression it causes is invisible to
    # it. Measured: `max_bars=24` regresses `split-many-bars` (19 colliding labels) while moving
    # `mean_style` by 0.000. A candidate that breaks a figure must be rejected whatever it does to
    # typography, so the per-task check below always reads `score`.
    _score_base = probe_result["mean_score"]["baseline"]
    decisions = []
    for cand in space.candidates:
        if cand.id not in outcomes:
            raise MutationError(
                f"candidate {cand.id!r} was proposed but never probed; refusing to compose a "
                f"decision from a partial probe")
        score = _means[cand.id]
        delta = round(score - base, 6)
        per_task = outcomes[cand.id]
        changed = [tid for tid, row in per_task.items()
                   if (row["outcome"], row["score"]) !=
                   (outcomes["baseline"][tid]["outcome"], outcomes["baseline"][tid]["score"])]
        drops = []
        for tid, row in per_task.items():
            fell = round(outcomes["baseline"][tid]["score"] - row["score"], 6)
            if fell >= margin:
                drops.append({"task": tid, "fell_by": fell,
                              "outcome": row["outcome"],
                              "expected": row.get("expected"),
                              "detail": row.get("detail", "")})
        # WHEN A TASK REGRESSES, THE DELTA MUST BE THE ONE THE REGRESSION LIVES IN.
        #
        # `delta` above is the style aggregate's; `drops` are per-task `score` falls. A candidate can
        # be rejected for a `score` regression while its style delta is positive, and reporting the
        # positive number beside "regresses split-many-bars" is incoherent -- a test refused it.
        # The refusal classifier's own mean is therefore what the verdict sees when it is available.
        _score_delta = round(probe_result["mean_score"][cand.id] - _score_base, 6)
        delta_for_verdict = _score_delta if drops else delta
        verdict, reason = _verdict(delta_for_verdict, drops, margin, score, space.min_score)
        if verdict == "selected":
            reason = f"{reason}; changed tasks: {changed or 'none'}"
        elif drops:
            reason = f"{reason}; changed tasks: {changed or 'none'}"
        # THE DECISION MUST NOT DEPEND ON THE CANDIDATE'S SHAPE. A scalar candidate names an
        # operator parameter; a PATCH candidate names a file and two texts. Reading the scalar
        # fields directly meant `compose` could only ever judge scalars -- which is why the loop's
        # discovery channel was five integers. The verdict comes from the scores either way.
        decisions.append({
            "id": cand.id,
            "operator": getattr(cand, "operator", None),
            "parameter": getattr(cand, "parameter", None),
            "value": getattr(cand, "value", None),
            "baseline_value": getattr(cand, "baseline_value", None),
            "score_delta": round(probe_result["mean_score"][cand.id] - _score_base, 6),
            "kind": ("patch" if getattr(cand, "old", None) is not None else "scalar"),
            "patch_path": getattr(cand, "path", None),
            "score": score, "baseline_score": base, "delta": delta_for_verdict,
            "verdict": verdict, "reason": reason,
            "changed_tasks": changed, "regressed_tasks": drops,
            "per_task": {tid: {"outcome": row["outcome"], "score": row["score"],
                               "expected": row.get("expected"),
                               "detail": row.get("detail", "")}
                         for tid, row in per_task.items()},
        })
    selected = [d["id"] for d in decisions if d["verdict"] == "selected"]
    ties = [d["id"] for d in decisions if d["verdict"] == "tie"]
    rejected = [d["id"] for d in decisions if d["verdict"] == "rejected"]
    return {
        "baseline_score": base,
        # WHICH AGGREGATE DECIDED. `mean_score` is the refusal classifier and is 1.0 for every task in
        # the pool, so a tie on it means "this aggregate cannot see", not "the candidates are equal".
        # `mean_style` is the one with resolution, and only a task set that declares references has it.
        "aggregate": aggregate,
        "min_margin": margin,
        "decisions": decisions,
        "selected": selected,
        "ties": ties,
        "rejected": rejected,
        "verdict": ("selected" if selected else "tie" if ties else
                    "rejected" if rejected else "no-candidates"),
        "rule": ("select only when the candidate beats the baseline on the SAME fixed task set "
                 "by at least min_margin AND no task regresses by min_margin or more; reject on "
                 "any such regression; report a tie as a tie. A refusal scores 1.0 only when "
                 "the task declares that refusing is the right outcome."),
        "ledger": probe_result.get("ledger"),
    }


