# Compose
# --------------------------------------------------------------------------------------

def _verdict(delta: float, drops: list, margin: float) -> tuple[str, str]:
    """The decision rule, as one pure function: (verdict, reason) for one candidate.

    Kept separate from `compose` so it can be INVERTED by a test. `tests/test_mutation.py` swaps
    this function for one that selects on a regression and rejects on an improvement, and asserts
    that the selection tests then FAIL. A test that cannot fail is not a test (LEARNINGS ##48);
    a decision rule that cannot be shown to matter is not a control either.
    """
    if drops:
        worst = max(drops, key=lambda d: d["fell_by"])
        return "rejected", (
            f"regresses {len(drops)} task(s) on the fixed set, worst {worst['task']!r} by "
            f"-{worst['fell_by']:.3f} (>= margin {margin}); a task that gets worse is a "
            f"regression whatever the mean says")
    if delta >= margin:
        return "selected", (
            f"improves the fixed task set by {delta:+.3f} (>= margin {margin}) with no task "
            f"regressing")
    if delta <= -margin:
        return "rejected", (
            f"regresses the fixed task set by {delta:+.3f} (<= -margin {margin})")
    if delta > 0:
        return "tie", (
            f"improves by {delta:+.3f}, below the margin {margin}: smaller than the decision "
            f"threshold, so it is reported as a tie rather than picked")
    return "tie", (
        f"no measurable difference on the fixed task set ({delta:+.3f}); the task set cannot "
        f"distinguish this edit from the baseline, so it is reported as a tie")


def compose(probe_result: dict, space: MutationSpace, *,
            min_margin: float | None = None) -> dict:
    """Decide from the behavioural contrast; a tie is reported, never resolved.

    TWO conditions, because one is not enough:

    1. NO TASK MAY REGRESS. If any task's score falls by `min_margin` or more, the candidate is
       REJECTED whatever the mean says. This is the same rule the scheduled loop applies to
       capability fields (a judged field that gets worse fails the run), and it is here for a
       concrete reason: `max_rows=60` fixes the 41-row table AND makes the 48-row table collide,
       which nets out to +0.002 on the mean. A mean that cancels a broken figure against a fixed
       one is the "a mean over a set hides the case that matters" defect this project has
       recorded repeatedly (##25, ##26, ##30). The margin is the measurement's resolution, so a
       drop smaller than it is not a regression.
    2. THE MEAN MUST MOVE BY THE MARGIN. A candidate is SELECTED only when it beats the baseline
       by `min_margin` or more, in the same shape as `select.should_transfer` (keep the plain
       figure unless the styled one is at least `min_margin` closer). Otherwise it is a TIE.

    The three verdicts are different kinds of information and are kept apart on purpose: a
    REJECTION with a reason says "this edit does not help, and here is which task showed it"; a
    TIE says "the task set cannot distinguish these"; and picking one silently would be neither.
    """
    margin = space.min_margin if min_margin is None else float(min_margin)
    outcomes = probe_result["outcomes"]
    if "baseline" not in outcomes:
        raise MutationError("probe result has no baseline row; nothing to contrast against")
    base = probe_result["mean_score"]["baseline"]
    decisions = []
    for cand in space.candidates:
        if cand.id not in outcomes:
            raise MutationError(
                f"candidate {cand.id!r} was proposed but never probed; refusing to compose a "
                f"decision from a partial probe")
        score = probe_result["mean_score"][cand.id]
        delta = round(score - base, 6)
        per_task = outcomes[cand.id]
        changed = [tid for tid, row in per_task.items()
                   if (row["outcome"], row["score"]) !=
                   (outcomes["baseline"][tid]["outcome"], outcomes["baseline"][tid]["score"])]
        drops = []
        for tid, row in per_task.items():
            fell = round(outcomes["baseline"][tid]["score"] - row["score"], 6)
            if fell >= margin:
                drops.append({"task": tid, "fell_by": fell,
                              "outcome": row["outcome"],
                              "expected": row.get("expected"),
                              "detail": row.get("detail", "")})
        verdict, reason = _verdict(delta, drops, margin)
        if verdict == "selected":
            reason = f"{reason}; changed tasks: {changed or 'none'}"
        elif drops:
            reason = f"{reason}; changed tasks: {changed or 'none'}"
        decisions.append({
            "id": cand.id, "operator": cand.operator, "parameter": cand.parameter,
            "value": cand.value, "baseline_value": cand.baseline_value,
            "score": score, "baseline_score": base, "delta": delta,
            "verdict": verdict, "reason": reason,
            "changed_tasks": changed, "regressed_tasks": drops,
            "per_task": {tid: {"outcome": row["outcome"], "score": row["score"],
                               "expected": row.get("expected"),
                               "detail": row.get("detail", "")}
                         for tid, row in per_task.items()},
        })
    selected = [d["id"] for d in decisions if d["verdict"] == "selected"]
    ties = [d["id"] for d in decisions if d["verdict"] == "tie"]
    rejected = [d["id"] for d in decisions if d["verdict"] == "rejected"]
    return {
        "baseline_score": base,
        "min_margin": margin,
        "decisions": decisions,
        "selected": selected,
        "ties": ties,
        "rejected": rejected,
        "verdict": ("selected" if selected else "tie" if ties else
                    "rejected" if rejected else "no-candidates"),
        "rule": ("select only when the candidate beats the baseline on the SAME fixed task set "
                 "by at least min_margin AND no task regresses by min_margin or more; reject on "
                 "any such regression; report a tie as a tie. A refusal scores 1.0 only when "
                 "the task declares that refusing is the right outcome."),
        "ledger": probe_result.get("ledger"),
    }


